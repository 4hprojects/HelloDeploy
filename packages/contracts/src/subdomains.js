export function normalizeSubdomainLabel(value) {
  return String(value ?? '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 63);
}

export function isReservedSubdomain(label) {
  return RESERVED_SUBDOMAINS.has(String(label).toLowerCase());
}

export function isValidSubdomainLabel(label) {
  return (
    Boolean(label) && label.length <= 63 && /^(?:[a-z0-9]|[a-z0-9][a-z0-9-]*[a-z0-9])$/.test(label)
  );
}
