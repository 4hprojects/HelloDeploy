import {
  APPROVED_PYTHON_VERSIONS,
  BuildStrategy,
  RuntimeType,
  isPythonBuildStrategy,
  validateApplicationModule,
} from '@hellodeploy/contracts';
import { assertNoControlChars } from '@hellodeploy/security';
import { ImageTemplateVersion } from './template-policy.js';

// Node.js LTS version pinned to avoid drift between builds
const NODE_IMAGE = 'node:22-alpine';
const NEXT_NODE_IMAGE = 'node:22-bookworm-slim';
// Versioned Next.js images set HOSTNAME because Docker defaults it to the
// container id, and Next servers bind to it instead of every interface.
// Unprivileged variant: runs as uid 101 and listens on STATIC_PORT instead of 80,
// so static containers never run nginx as root.
const NGINX_IMAGE = 'nginxinc/nginx-unprivileged:1.27-alpine';

// Fixed unprivileged uid for Python images, which ship no non-root user.
const PYTHON_APP_UID = 10001;

/** Container-internal port nginx-unprivileged listens on for static runtimes. */
export const STATIC_PORT = 8080;

// Build commands come from package.json scripts (`next build`, `vite build`) or
// are typed by the user, so they assume the PATH npm gives a script. A bare
// Dockerfile RUN uses /bin/sh, which has no node_modules/.bin, and every such
// command dies with "not found" (exit 127) unless we put it back.
const LOCAL_BIN_PATH = '/app/node_modules/.bin:$PATH';

/** Mirrors the EnvironmentSecret model's name validation. */
const VALID_BUILD_ARG_NAME = /^[A-Z_][A-Z0-9_]*$/;

/**
 * Declare build arguments and re-export them as environment variables so the
 * build command can read them. ARG alone is not enough — it is visible to the
 * Dockerfile, not to the process RUN starts.
 */
function buildArgDeclarations(names) {
  // Each entry carries its own trailing newline so an empty list contributes
  // nothing rather than a blank line.
  return names.map((name) => `ARG ${name}\nENV ${name}=$${name}\n`).join('');
}

/**
 * Generate a safe Dockerfile for the detected runtime.
 * SECURITY: Dockerfiles are always generated by the platform — user Dockerfiles
 * are removed from the build context in `prepareBuildContext`.
 *
 * @param {{ runtimeType: string, buildCommand: string|null, startCommand: string|null, outputDirectory: string|null, applicationPort: number|null }} config
 * @returns {string} Dockerfile content
 */
export function generateDockerfile(config) {
  const {
    runtimeType,
    buildCommand,
    startCommand,
    outputDirectory,
    applicationPort,
    buildArgNames = [],
    templateVersion = ImageTemplateVersion.LEGACY,
    buildStrategy = BuildStrategy.LEGACY_GENERATED,
    applicationModule = null,
    pythonVersion = null,
  } = config;

  if (!Object.values(ImageTemplateVersion).includes(templateVersion)) {
    throw new Error(`Unsupported image template version: ${templateVersion}`);
  }

  // Names are interpolated into ARG/ENV directives. They reach here from the
  // EnvironmentSecret collection, which validates the same shape on write, but
  // this is the last point before templating and must not trust that.
  for (const name of buildArgNames) {
    if (!VALID_BUILD_ARG_NAME.test(name)) {
      throw new Error(`Invalid build argument name: ${name}`);
    }
  }

  // Independent re-check right before templating: these values are interpolated
  // raw into RUN/CMD/COPY instructions below. The web form validator is the
  // primary guard (project.validator.js), but this must not be the only one —
  // any other write path to these fields would otherwise reach the Dockerfile
  // unchecked and inject arbitrary directives via a newline.
  if (buildCommand) {
    assertNoControlChars(buildCommand, 'Build command');
  }
  if (startCommand) {
    assertNoControlChars(startCommand, 'Start command');
  }
  if (outputDirectory) {
    assertNoControlChars(outputDirectory, 'Output directory');
  }

  if (isPythonBuildStrategy(buildStrategy)) {
    if (runtimeType !== RuntimeType.PYTHON) {
      throw new Error(`The ${buildStrategy} build strategy requires the PYTHON runtime.`);
    }
    // Re-checked here because the module is templated into CMD and the version
    // into FROM; the web validator and the job are not the only write paths.
    const moduleError = validateApplicationModule(applicationModule);
    if (moduleError) {
      throw new Error(moduleError);
    }
    if (!APPROVED_PYTHON_VERSIONS.includes(pythonVersion)) {
      throw new Error(`Unsupported Python version: ${pythonVersion}`);
    }
    return generatePython({
      buildStrategy,
      buildCommand,
      buildArgNames,
      applicationModule,
      applicationPort: applicationPort ?? 8000,
      pythonVersion,
    });
  }

  switch (runtimeType) {
    case RuntimeType.STATIC:
      return generateStatic();

    case RuntimeType.REACT:
    case RuntimeType.VUE:
      return generateStaticBuild({
        buildCommand: buildCommand ?? 'npm run build',
        outputDirectory: outputDirectory ?? 'dist',
        buildArgNames,
      });

    case RuntimeType.NEXTJS:
      if (buildStrategy === BuildStrategy.NEXT_STANDARD_V1) {
        return generateNextStandard({
          buildCommand: buildCommand ?? 'npm run build',
          buildArgNames,
          applicationPort: applicationPort ?? 3000,
        });
      }
      if (buildStrategy === BuildStrategy.NEXT_STANDALONE_V1) {
        return generateNextStandaloneV1({
          buildCommand: buildCommand ?? 'npm run build',
          buildArgNames,
          applicationPort: applicationPort ?? 3000,
        });
      }
      if (buildStrategy === BuildStrategy.NEXT_EXPORT_V1) {
        return generateNextExport({
          buildCommand: buildCommand ?? 'npm run build',
          buildArgNames,
        });
      }
      return generateNextjs({
        buildCommand: buildCommand ?? 'npm run build',
        buildArgNames,
        ensurePublicDirectory: templateVersion === ImageTemplateVersion.OPTIMIZED_V1,
      });

    case RuntimeType.EXPRESS:
    case RuntimeType.NODEJS:
      return generateNode({
        buildCommand,
        startCommand: startCommand ?? 'node server.js',
        applicationPort: applicationPort ?? 3000,
        optimized: templateVersion === ImageTemplateVersion.OPTIMIZED_V1,
      });

    default:
      throw new Error(`Cannot generate Dockerfile for unsupported runtime: ${runtimeType}`);
  }
}

function generateNextStandard({ buildCommand, buildArgNames, applicationPort }) {
  return `FROM ${NEXT_NODE_IMAGE} AS builder
WORKDIR /app
COPY package*.json ./
RUN npm ci --prefer-offline
COPY . .
${buildArgDeclarations(buildArgNames)}ENV PATH=${LOCAL_BIN_PATH}
ENV NEXT_TELEMETRY_DISABLED=1
RUN ${buildCommand}
RUN npm prune --omit=dev

FROM ${NEXT_NODE_IMAGE}
WORKDIR /app
ENV NODE_ENV=production
COPY --from=builder --chown=node:node /app ./
USER node
EXPOSE ${applicationPort}
ENV PORT=${applicationPort}
ENV HOSTNAME=0.0.0.0
CMD ["npm", "start"]
`;
}

function generateNextStandaloneV1({ buildCommand, buildArgNames, applicationPort }) {
  return `FROM ${NEXT_NODE_IMAGE} AS deps
WORKDIR /app
COPY package*.json ./
RUN npm ci --prefer-offline

FROM ${NEXT_NODE_IMAGE} AS builder
WORKDIR /app
COPY --from=deps /app/node_modules ./node_modules
COPY . .
${buildArgDeclarations(buildArgNames)}ENV PATH=${LOCAL_BIN_PATH}
ENV NEXT_TELEMETRY_DISABLED=1
RUN ${buildCommand}
RUN mkdir -p /app/public

FROM ${NEXT_NODE_IMAGE}
WORKDIR /app
ENV NODE_ENV=production
COPY --from=builder --chown=node:node /app/.next/standalone ./
COPY --from=builder --chown=node:node /app/.next/static ./.next/static
COPY --from=builder --chown=node:node /app/public ./public
USER node
EXPOSE ${applicationPort}
ENV PORT=${applicationPort}
ENV HOSTNAME=0.0.0.0
CMD ["node", "server.js"]
`;
}

function generateNextExport({ buildCommand, buildArgNames }) {
  return `FROM ${NEXT_NODE_IMAGE} AS builder
WORKDIR /app
COPY package*.json ./
RUN npm ci --prefer-offline
COPY . .
${buildArgDeclarations(buildArgNames)}ENV PATH=${LOCAL_BIN_PATH}
ENV NEXT_TELEMETRY_DISABLED=1
RUN ${buildCommand}

FROM ${NGINX_IMAGE}
COPY --from=builder /app/out /usr/share/nginx/html
EXPOSE ${STATIC_PORT}
CMD ["nginx", "-g", "daemon off;"]
`;
}

function generatePython({
  buildStrategy,
  buildCommand,
  buildArgNames,
  applicationModule,
  applicationPort,
  pythonVersion,
}) {
  const image = `python:${pythonVersion}-slim-bookworm`;
  // The proxy is the only client that can reach the loopback-published port, so
  // trusting its forwarded headers lets apps see the public https scheme.
  const command =
    buildStrategy === BuildStrategy.PYTHON_FASTAPI_V1
      ? [
          'uvicorn',
          applicationModule,
          '--host',
          '0.0.0.0',
          '--port',
          String(applicationPort),
          '--proxy-headers',
          '--forwarded-allow-ips',
          '*',
        ]
      : [
          'gunicorn',
          '--bind',
          `0.0.0.0:${applicationPort}`,
          '--workers',
          '2',
          '--forwarded-allow-ips',
          '*',
          '--access-logfile',
          '-',
          applicationModule,
        ];
  return `FROM ${image} AS builder
ENV PYTHONDONTWRITEBYTECODE=1 PIP_DISABLE_PIP_VERSION_CHECK=1 PIP_NO_CACHE_DIR=1
RUN python -m venv /opt/venv
ENV PATH=/opt/venv/bin:$PATH
WORKDIR /app
COPY . .
RUN pip install -r requirements.txt
${buildArgDeclarations(buildArgNames)}${buildCommand ? `RUN ${buildCommand}\n` : ''}
FROM ${image}
ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PATH=/opt/venv/bin:$PATH
RUN useradd --system --uid ${PYTHON_APP_UID} --no-create-home --shell /usr/sbin/nologin app
WORKDIR /app
COPY --from=builder /opt/venv /opt/venv
COPY --from=builder /app ./
USER ${PYTHON_APP_UID}
EXPOSE ${applicationPort}
ENV PORT=${applicationPort}
CMD ${JSON.stringify(command)}
`;
}

// ─── Per-runtime templates ─────────────────────────────────────────────────────

function generateStatic() {
  return `FROM ${NGINX_IMAGE}
COPY . /usr/share/nginx/html
EXPOSE ${STATIC_PORT}
CMD ["nginx", "-g", "daemon off;"]
`;
}

function generateStaticBuild({ buildCommand, outputDirectory, buildArgNames }) {
  return `FROM ${NODE_IMAGE} AS builder
WORKDIR /app
COPY package*.json ./
RUN npm ci --prefer-offline
COPY . .
${buildArgDeclarations(buildArgNames)}ENV PATH=${LOCAL_BIN_PATH}
RUN ${buildCommand}

FROM ${NGINX_IMAGE}
COPY --from=builder /app/${outputDirectory} /usr/share/nginx/html
EXPOSE ${STATIC_PORT}
CMD ["nginx", "-g", "daemon off;"]
`;
}

function generateNextjs({ buildCommand, buildArgNames, ensurePublicDirectory }) {
  return `FROM ${NODE_IMAGE} AS deps
WORKDIR /app
COPY package*.json ./
RUN npm ci --prefer-offline

FROM ${NODE_IMAGE} AS builder
WORKDIR /app
COPY --from=deps /app/node_modules ./node_modules
COPY . .
${buildArgDeclarations(buildArgNames)}ENV PATH=${LOCAL_BIN_PATH}
RUN ${buildCommand}
${ensurePublicDirectory ? 'RUN mkdir -p /app/public\n' : ''}
FROM ${NODE_IMAGE}
WORKDIR /app
ENV NODE_ENV=production
COPY --from=builder --chown=node:node /app/.next/standalone ./
COPY --from=builder --chown=node:node /app/.next/static ./.next/static
COPY --from=builder --chown=node:node /app/public ./public
USER node
EXPOSE 3000
ENV PORT=3000
CMD ["node", "server.js"]
`;
}

function generateNode({ buildCommand, startCommand, applicationPort, optimized }) {
  // Keep the approved start command as one JSON-encoded shell argument. This
  // preserves common package-script operators such as `&&` without allowing a
  // newline to inject another Dockerfile directive (guarded above).
  const cmdJson = JSON.stringify(['sh', '-c', startCommand]);

  // Apps that compile before starting (TypeScript, bundlers) need their dev
  // dependencies for the build only. Source is copied before `npm ci` because
  // postinstall/prepare scripts may need it; pruning afterwards leaves the same
  // production-only node_modules the single-stage templates ship.
  if (buildCommand) {
    return `FROM ${NODE_IMAGE} AS builder
WORKDIR /app
COPY . .
RUN npm ci --prefer-offline
ENV PATH=${LOCAL_BIN_PATH}
RUN ${buildCommand}
RUN npm prune --omit=dev

FROM ${NODE_IMAGE}
WORKDIR /app
ENV NODE_ENV=production
COPY --from=builder --chown=node:node /app ./
USER node
EXPOSE ${applicationPort}
ENV PORT=${applicationPort}
CMD ${cmdJson}
`;
  }

  if (optimized) {
    return `FROM ${NODE_IMAGE} AS deps
WORKDIR /app
COPY package*.json ./
RUN npm ci --prefer-offline --omit=dev

FROM ${NODE_IMAGE}
WORKDIR /app
ENV NODE_ENV=production
COPY --from=deps --chown=node:node /app/node_modules ./node_modules
COPY --chown=node:node . .
USER node
EXPOSE ${applicationPort}
ENV PORT=${applicationPort}
CMD ${cmdJson}
`;
  }

  return `FROM ${NODE_IMAGE}
WORKDIR /app
COPY --chown=node:node . .
RUN npm ci --prefer-offline --omit=dev
USER node
EXPOSE ${applicationPort}
ENV PORT=${applicationPort}
CMD ${cmdJson}
`;
}
